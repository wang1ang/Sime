#!/usr/bin/env python3
"""Generate src/reading.inc: how unlikely each reading of a character is.

The LM scores characters, not readings, so a common character typed with a
rare reading (厂 as an, 都 as du) inherits its full frequency. The table gives
-ln(count(reading) / count(most frequent reading)) per character, so the main
reading costs 0. A listed character typed with an unlisted reading gets the
cap.

Sources, per reading, first one that lists it wins (each normalized to its
own top reading):
  1. Unihan kHanyuPinlu (corpus counts from 现代汉语频率词典, ~3800 chars).
     https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip
  2. rime-ice cn_dicts/8105.dict.yaml weights; adds colloquial readings
     Unihan lacks (这 zhei, 谁 shei).
     https://github.com/iDvel/rime-ice
  3. COLLOQUIAL below, for readings neither lists.

Usage:
  gen_reading_prior.py Unihan_Readings.txt 8105.dict.yaml ../src/reading.inc
"""

import math
import re
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

# Keep in sync with Sime::ReadingCostCap and the quantization in sime.cc.
CAP = 8.0
SCALE = 16


# Colloquial readings neither source lists, typed often enough to be free.
COLLOQUIAL = {"那": ["nei"], "哪": ["nei"]}


def load_syllables(dict_inc):
    return set(re.findall(r'\{ "([a-z]+)",', Path(dict_inc).read_text()))


def plain(reading):
    """dōu -> dou, lǜ -> lv, xué -> xue (the spelling sime.dict uses)."""
    s = unicodedata.normalize("NFD", reading.strip().lower())
    s = s.replace("ü", "v")
    s = "".join(c for c in s if not unicodedata.combining(c))
    if s[:1] in "jqxy":
        s = s.replace("v", "u")
    return s


def load_unihan(path):
    counts = defaultdict(lambda: defaultdict(int))
    for line in open(path, encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) != 3 or parts[1] != "kHanyuPinlu":
            continue
        ch = chr(int(parts[0][2:], 16))
        for m in re.finditer(r"([^\s(]+)\((\d+)\)", parts[2]):
            counts[ch][plain(m.group(1))] += int(m.group(2))
    return counts


def load_rime(path):
    counts = defaultdict(lambda: defaultdict(int))
    body = False
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line == "...":
            body = True
            continue
        if not body or not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2 or len(parts[0]) != 1:
            continue
        weight = int(parts[2]) if len(parts) > 2 and parts[2].isdigit() else 0
        counts[parts[0]][plain(parts[1])] += max(weight, 1)
    return counts


def main():
    unihan_path, rime_path, out_path = sys.argv[1:4]
    syllables = load_syllables(Path(__file__).resolve().parent.parent / "src" / "dict.inc")
    unihan = load_unihan(unihan_path)
    rime = load_rime(rime_path)

    rows = []
    for ch in sorted(set(unihan) | set(rime) | set(COLLOQUIAL), key=ord):
        costs = {}
        for source in (unihan.get(ch), rime.get(ch)):
            readings = {r: c for r, c in (source or {}).items() if r in syllables}
            if not readings:
                continue
            top = max(readings.values())
            for r, c in readings.items():
                costs.setdefault(r, min(CAP, -math.log(c / top)))
        for r in COLLOQUIAL.get(ch, []):
            costs[r] = 0.0
        for r, cost in sorted(costs.items()):
            rows.append((ord(ch), r, round(cost * SCALE)))

    with open(out_path, "w", encoding="utf-8") as out:
        out.write("// Generated by pipeline/gen_reading_prior.py; do not edit.\n")
        out.write("// {code point, reading, -ln(P(reading) / P(top reading)) * "
                  f"{SCALE}}}, sorted.\n")
        for cp, r, q in rows:
            out.write(f'    {{ 0x{cp:05x}, "{r}", {q} }},\n')
    print(f"{len(rows)} readings for {len({r[0] for r in rows})} characters",
          file=sys.stderr)


if __name__ == "__main__":
    main()
